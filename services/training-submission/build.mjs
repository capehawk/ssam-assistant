import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const output=path.join(root,'dist');
await mkdir(output,{recursive:true});
const modules=['fixtures.js','core.js','application.js','gas-adapters.js'];
const source=await Promise.all(modules.map(name=>readFile(path.join(root,name),'utf8')));
const body=source.map(text=>text.replace(/^import .*;\s*$/gm,'').replace(/^export /gm,'')).join('\n');
const bundle=`// Generated by node services/training-submission/build.mjs; edit source files.\nvar TrainingModule_ = (function() {\n'use strict';\n${body}\nreturn {createTrainingService,createTokenAuthenticator,createApplication,createSheetRepository,createDriveEvidenceStore,DEMO_CATALOG};\n})();\n`;
await writeFile(path.join(output,'Training.gs'),bundle);
await Promise.all(['entry.gs','Reviewer.html','appsscript.json'].map(name=>copyFile(path.join(root,'gas',name),path.join(output,name))));
console.log('Built services/training-submission/dist (copy these four files into Apps Script).');
